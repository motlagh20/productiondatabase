function initializeSettingTransactions() {
  const perSel = document.getElementById('setting-filter-per-page');
  const dateInp = document.getElementById('setting-filter-date');
  const chamberInp = document.getElementById('setting-filter-chamber');
  const applyBtn = document.getElementById('setting-apply-filters');
  const clearBtn = document.getElementById('setting-clear-filters');
  const firstBtn = document.getElementById('setting-page-first');
  const prevBtn = document.getElementById('setting-page-prev');
  const nextBtn = document.getElementById('setting-page-next');
  const lastBtn = document.getElementById('setting-page-last');
  if (perSel) settingState.perPage = parseInt(perSel.value || '10');
  if (applyBtn) applyBtn.onclick = () => { settingState.filters.date = (dateInp && dateInp.value || '').trim(); settingState.filters.chamber = (chamberInp && chamberInp.value || '').trim(); settingState.page = 1; loadSettingTransactions(); };
  if (clearBtn) clearBtn.onclick = () => { if (dateInp) dateInp.value=''; if (chamberInp) chamberInp.value=''; settingState.filters = { date:'', chamber:'' }; settingState.page = 1; loadSettingTransactions(); };
  if (perSel) perSel.onchange = () => { settingState.perPage = parseInt(perSel.value || '10'); settingState.page = 1; loadSettingTransactions(); };
  if (firstBtn) firstBtn.onclick = () => { settingState.page = 1; loadSettingTransactions(); };
  if (prevBtn) prevBtn.onclick = () => { settingState.page = Math.max(1, settingState.page - 1); loadSettingTransactions(); };
  if (nextBtn) nextBtn.onclick = () => { settingState.page = Math.min(settingState.totalPages, settingState.page + 1); loadSettingTransactions(); };
  if (lastBtn) lastBtn.onclick = () => { settingState.page = settingState.totalPages; loadSettingTransactions(); };
  loadSettingTransactions();
}
async function loadSettingTransactions() {
  const tbody = document.getElementById('setting-transactions-body');
  const totalDiv = document.getElementById('setting-total-count');
  const pageLabel = document.getElementById('setting-page-label');
  if (tbody) tbody.innerHTML = '<tr><td colspan="17">Loading...</td></tr>';
  try {
    const params = new URLSearchParams();
    params.set('page', String(settingState.page));
    params.set('per_page', String(settingState.perPage));
    params.set('order', settingState.order);
    if (settingState.filters.date) params.set('date', settingState.filters.date.trim());
    if (settingState.filters.chamber) params.set('chamber', settingState.filters.chamber.trim());
    const r = await fetch(`/api/rpc/get_setting_transactions?${params.toString()}`);
    const j = await r.json();
    if (!r.ok) throw new Error(j && j.error ? j.error : 'خطا در دریافت تراکنش‌ها');
    const items = Array.isArray(j.transactions) ? j.transactions : [];
    settingState.totalCount = j.total_count || items.length;
    settingState.totalPages = j.total_pages || 1;
    let filtered = items;
    if (settingState.filters.date) filtered = filtered.filter(tx => String(tx.TransactionDate || '').trim() === settingState.filters.date.trim());
    if (settingState.filters.chamber) filtered = filtered.filter(tx => String(tx.ChamberID_FK || '').trim() === settingState.filters.chamber.trim());
    if (tbody) {
      if (filtered.length === 0) tbody.innerHTML = '<tr><td colspan="10" class="text-center text-muted" style="padding: var(--spacing-xl);">هیچ رکوردی یافت نشد</td></tr>';
      else {
        const startIndex = (settingState.page - 1) * settingState.perPage;
        tbody.innerHTML = filtered.map((tx, idx) => `
          <tr>
            <td class="text-center">${toPersianDigits(startIndex + idx + 1)}</td>
            <td class="text-center"><span class="badge badge-primary">${toPersianDigits(tx.ChamberNo)}</span></td>
            <td class="text-center">${toPersianDigits(tx.SettingDateJalali || '-')}</td>
            <td class="text-center">${tx.ShiftName || '-'}</td>
            <td>${tx.OperatorName || '-'}</td>
            <td title="${tx.ProductName || ''}">${tx.ProductName || '-'}</td>
            <td class="text-center">${toPersianDigits(tx.FingersCount || 0)}</td>
            <td class="text-center">${toPersianDigits(tx.DryerWaste || 0)}</td>
            <td style="font-size: 0.85em; white-space: pre-line; direction: ltr; text-align: center;">${toPersianDigits(tx.WagonNos || '-').replace(/\s-\s/g, '\n')}</td>
            <td class="text-center">
              <button type="button" class="btn btn-sm btn-outline" data-act="edit-setting" data-id="${tx.SettingID}">ویرایش</button>
            </td>
          </tr>
        `).join('');
      }
    }
    if (totalDiv) totalDiv.textContent = `تعداد کل: ${settingState.totalCount}`;
    if (pageLabel) pageLabel.textContent = `${settingState.page} / ${settingState.totalPages}`;
  } catch(err) {
    if (tbody) tbody.innerHTML = `<tr><td colspan="17">${err.message}</td></tr>`;
  }
}

