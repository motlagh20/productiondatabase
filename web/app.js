const glazesCache = { list: [] };

async function loadGlazes() {
  if (glazesCache.list.length) return glazesCache.list;
  try {
    const r = await fetch('/api/glazes');
    const rows = await r.json();
    glazesCache.list = rows;
    return rows;
  } catch(e) { return []; }
}

function renderWagonRow(tbody, idx, defaults = {}) {
  const ord = defaults.wagon_order ?? (idx+1);
  const wn = defaults.wagon_no ?? '';
  const pk = defaults.packages ?? '';
  const st = defaults.start_time ?? '';
  const et = defaults.end_time ?? '';
  const glazeSel = `<select data-edit="glaze_id"><option value="">انتخاب...</option>${glazesCache.list.map(g=>`<option value="${g.GlazeID}" ${String(g.GlazeID)===String(defaults.glaze_id||'')?'selected':''}>${g.GlazeName}</option>`).join('')}</select>`;
  const tr = document.createElement('tr');
  tr.innerHTML = `
    <td><input type="number" value="${ord}" min="1" max="4" data-edit="wagon_order"></td>
    <td><input type="number" value="${wn}" data-edit="wagon_no"></td>
    <td>${glazeSel}</td>
    <td><input type="text" value="${defaults.extra_code||''}" data-edit="extra_code" placeholder="-01 یا -LG"></td>
    <td><input type="text" value="${st}" data-edit="start_time" placeholder="HH:MM"></td>
    <td><input type="text" value="${et}" data-edit="end_time" placeholder="HH:MM"></td>
    <td><input type="number" value="${pk}" data-edit="packages" min="0"></td>
    <td>
      <button type="button" class="btn btn-sm btn-outline" data-act="save-row">ذخیره</button>
      <button type="button" class="btn btn-sm btn-danger" data-act="del-wagon">حذف</button>
    </td>
  `;
  if (defaults.wagon_id) tr.dataset.id = defaults.wagon_id;
  tbody.appendChild(tr);
}

