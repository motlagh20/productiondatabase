function toEnglishDigits(str) {
  const persianDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  return String(str || '').replace(/[۰-۹]/g, w => persianDigits.indexOf(w));
}

function normalizeJalaliDate(str) {
  const s = toEnglishDigits(String(str || '').trim());
  const digits = s.replace(/\D/g, '');
  let y, m, d;
  const m1 = s.match(/^(\d{4})\D?(\d{1,2})\D?(\d{1,2})$/);
  if (m1) {
    y = parseInt(m1[1], 10);
    m = parseInt(m1[2], 10);
    d = parseInt(m1[3], 10);
  } else if (digits.length === 8) {
    y = parseInt(digits.slice(0,4), 10);
    m = parseInt(digits.slice(4,6), 10);
    d = parseInt(digits.slice(6,8), 10);
  } else {
    return s;
  }
  if (!y || y < 1200 || y > 1600) y = parseInt(String(y || '').padStart(4,'0'), 10) || 1400;
  if (!m || m < 1) m = 1;
  if (m > 12) m = 12;
  if (!d || d < 1) d = 1;
  if (d > 31) d = 31;
  return `${String(y).padStart(4,'0')}/${String(m).padStart(2,'0')}/${String(d).padStart(2,'0')}`;
}

function toPersianDigits(str) {
  const persianDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  return String(str || '').replace(/[0-9]/g, w => persianDigits[w]);
}

function formatJalaliDate(str) {
  if (!str) return '-';
  return toPersianDigits(String(str).replace(/-/g, '/'));
}

function formatTime(str) {
  if (!str) return '-';
  const parts = String(str).split(':');
  if (parts.length >= 2) {
    return toPersianDigits(`${parts[0]}:${parts[1]}`);
  }
  return toPersianDigits(str);
}

const reTime24 = /^([0-1]?[0-9]|2[0-3]):[0-5][0-9]$/;
function isValidTime24(s) { return reTime24.test(toEnglishDigits(s).trim()); }
function normalizeTime24(s) {
  const clean = toEnglishDigits(s).trim();
  const m = clean.match(/^(\d{1,2}):([0-5]\d)$/);
  if (!m) return clean;
  let h = parseInt(m[1], 10);
  if (Number.isNaN(h)) return clean;
  if (h < 0) h = 0;
  if (h > 23) h = 23;
  return `${String(h).padStart(2,'0')}:${m[2]}`;
}
