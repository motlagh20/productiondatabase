window.saveInlineEdit = async function(id) {
  const chamber = document.getElementById(`edit-chamber-${id}`).value;
  const categoryId = document.getElementById(`edit-category-${id}`).value;
  const moldId = document.getElementById(`edit-mold-${id}`).value;
  const glazeId = document.getElementById(`edit-glaze-${id}`).value;
  const date = document.getElementById(`edit-date-${id}`).value;
  const time = document.getElementById(`edit-time-${id}`).value;
  const opId = document.getElementById(`edit-op-${id}`).value;
  const finger = document.getElementById(`edit-finger-${id}`).value;
  
  if (!isValidTime24(time)) {
    alert('فرمت ساعت نامعتبر است (HH:MM)');
    return;
  }
  
  const btn = document.querySelector(`tr[data-id="${id}"] button.btn-success`);
  if(btn) btn.disabled = true;
  
  try {
    const res = await fetch('/api/dryer/update_load', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        load_id: id,
        chamber_no: parseInt(chamber),
        category_id: categoryId ? parseInt(categoryId) : null,
        mold_id: moldId ? parseInt(moldId) : null,
        glaze_id: glazeId ? parseInt(glazeId) : null,
        load_date_jalali: normalizeJalaliDate(date),
        load_time: normalizeTime24(time),
        operator_id: opId ? parseInt(opId) : null,
        finger_count: parseInt(finger)
      })
    });
    
    if (res.ok) {
      loadDryerHistory(); // Refresh table
    } else {
      const err = await res.json();
      alert('خطا در ویرایش: ' + (err.error || 'Unknown error'));
      if(btn) btn.disabled = false;
    }
  } catch (e) {
    alert('خطا در ارتباط با سرور');
    if(btn) btn.disabled = false;
  }
};

