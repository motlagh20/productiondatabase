  // Category
  let catHtml = `<select class="edit-input" style="width:120px" id="edit-category-${id}">`;
  catHtml += `<option value="">-</option>`;
  if (cachedCategories && cachedCategories.length) {
    cachedCategories.forEach(c => {
      const cid = c.CategoryID ?? c.category_id;
      const cname = c.CategoryName ?? c.category_name;
      catHtml += `<option value="${cid}" ${String(cid) === String(current.categoryId) ? 'selected' : ''}>${cname}</option>`;
    });
  }
  if ((!cachedCategories || !cachedCategories.length) && current.categoryId) {
    catHtml += `<option value="${current.categoryId}" selected>شناسه ${current.categoryId}</option>`;
  }
  catHtml += `</select>`;
  
  // Mold (depends on category)
  let molds = [];
  const loadMoldsFor = async (cid) => {
    if (cachedMoldsByCategory[cid]) return cachedMoldsByCategory[cid];
    const url = cid ? `/api/molds?category_id=${cid}` : '/api/molds';
    const r = await fetch(url).then(x=>x.json()).catch(()=>[]);
    cachedMoldsByCategory[cid] = r || [];
    return cachedMoldsByCategory[cid];
  };
  molds = await loadMoldsFor(current.categoryId);
  let moldHtml = `<select class="edit-input" style="width:120px" id="edit-mold-${id}">`;
  moldHtml += `<option value="">-</option>`;
  if (Array.isArray(molds) && molds.length) {
    molds.forEach(m => {
      const mid = m.MoldID ?? m.mold_id;
      const mname = m.MoldName ?? m.mold_name;
      moldHtml += `<option value="${mid}" ${String(mid) === String(current.moldId) ? 'selected' : ''}>${mname}</option>`;
    });
  }
  if ((!Array.isArray(molds) || !molds.length) && current.moldId) {
    moldHtml += `<option value="${current.moldId}" selected>شناسه ${current.moldId}</option>`;
  }
  moldHtml += `</select>`;
  
  // Glaze
  let glazeHtml = `<select class="edit-input" style="width:120px" id="edit-glaze-${id}">`;
  glazeHtml += `<option value="">-</option>`;
  if (cachedGlazes && cachedGlazes.length) {
    cachedGlazes.forEach(g => {
      const gid = g.GlazeID ?? g.glaze_id;
      const gname = g.GlazeName ?? g.glaze_name;
      glazeHtml += `<option value="${gid}" ${String(gid) === String(current.glazeId) ? 'selected' : ''}>${gname}</option>`;
    });
  }
  if ((!cachedGlazes || !cachedGlazes.length) && current.glazeId) {
    glazeHtml += `<option value="${current.glazeId}" selected>شناسه ${current.glazeId}</option>`;
  }
  glazeHtml += `</select>`;
  
  // Date
  const dateHtml = `<input type="text" class="edit-input" style="width:80px" value="${current.date}" id="edit-date-${id}">`;
  
  // Time
  const timeHtml = `<input type="text" class="edit-input" style="width:60px" value="${current.time}" id="edit-time-${id}">`;
  
