function applyTranslations(lang) {
  const dict = i18n[lang] || i18n.fa;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  if (dict.page_title) document.title = dict.page_title;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.getAttribute('data-i18n');
    if (k && dict[k] !== undefined) el.textContent = dict[k];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const k = el.getAttribute('data-i18n-placeholder');
    if (k && dict[k] !== undefined) el.setAttribute('placeholder', dict[k]);
  });
}

const views = document.querySelectorAll('[data-view]');
const navButtons = document.querySelectorAll('[data-link]');

function show(view) {
  const o = window.ALLOW_TEMP_VIEW;
  if (window.ALLOWED_PAGES && !window.ALLOWED_PAGES.has(view) && o !== view) view = 'home';
  views.forEach(v => {
    if (v.getAttribute('data-view') === view) {
      v.classList.add('active');
      if(view === 'dryer_dashboard') loadDryerDashboard();
      if(view === 'dryer_load') { loadDryerHistory(); loadFormData(); }
      if(view === 'dryer_unload') { loadDryerUnloadHistory(); loadUnloadFormData(); }
      if(view === 'dryer_unload_setting') { initDryerUnloadSetting(); }
      if(view === 'dryer_readings') { loadReadingsRecent(); loadReadingsFormData(); }
      if(view === 'kiln_pushing') { loadKilnPushingFormData(); loadKilnPushingRecent(); }
      if(view === 'users') loadUsers();
      if(view === 'setting_entry') initializeSettingEntry();
      if(view === 'setting_transactions') initializeSettingTransactions();
      if(view === 'admin_roles') initAdminRoles();
      if(view === 'admin_shifts') initAdminShifts();
      if(view === 'admin_fuel') initAdminFuel();
      if(view === 'admin_users_roles') initAdminUsersRoles();
      if(view === 'admin_access') initAdminAccess();
      if(view === 'admin_glazes') initAdminGlazes();
      if(view === 'admin_molds') initAdminMolds();
      if(view === 'admin_categories') initAdminCategories();
    } else {
      v.classList.remove('active');
    }
  });
  if (o === view) window.ALLOW_TEMP_VIEW = null;
  
  // Update nav active state
  navButtons.forEach(b => {
    if(b.getAttribute('data-link') === view) b.classList.add('active');
    else b.classList.remove('active');
  });

  // Update Dropdown Parent Active State
  document.querySelectorAll('.dropdown').forEach(d => {
    const activeChild = d.querySelector('[data-link].active');
    const toggle = d.querySelector('.dropdown-toggle');
    if (toggle) {
      if (activeChild) toggle.classList.add('active');
      else toggle.classList.remove('active');
    }
  });
}

