document.addEventListener('click', e => {
  // Dropdown Toggles
  const toggle = e.target.closest('.dropdown-toggle');
  if (toggle) {
    e.preventDefault();
    e.stopPropagation();
    const dropdown = toggle.closest('.dropdown');
    // Close other dropdowns
    document.querySelectorAll('.dropdown').forEach(d => {
        if (d !== dropdown) d.classList.remove('open');
    });
    dropdown.classList.toggle('open');
    return;
  }
  
  // Close all dropdowns if clicked outside or on a link
  if (!e.target.closest('.dropdown-menu') || e.target.closest('[data-link]')) {
     document.querySelectorAll('.dropdown').forEach(d => d.classList.remove('open'));
  }

  // Handle delegated clicks for cards
  const card = e.target.closest('.card');
  if (card) navigate(card.getAttribute('data-link'));
  
  // Handle delegated clicks for navbar brand
  const brand = e.target.closest('.navbar-brand');
  if (brand) {
     e.preventDefault();
     navigate('home');
  }
});

