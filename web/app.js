async function initAdminUsersRoles() {
  const form = document.getElementById('admin-users-form');
  const body = document.getElementById('admin-users-body');
  const search = document.getElementById('admin-users-search');
  let roles = [];
  let usersAll = [];
  async function loadRoles() {
    const r = await fetch('/api/admin/roles');
    roles = await r.json();
  }
  async function loadUsers() {
    const r = await fetch('/api/admin/users');
    usersAll = await r.json();
    renderUsers();
    const checks = body.querySelectorAll('div[id^="roles_"]');
    for (const div of checks) {
      const uid = parseInt(div.getAttribute('data-user'));
      const rr = await fetch(`/api/rpc/get_user_roles?user_id=${uid}`);
      const current = await rr.json();
      div.querySelectorAll('input[type="checkbox"]').forEach(ch => { ch.checked = current.includes(parseInt(ch.value)); });
      div.onchange = async () => {
        const sel = Array.from(div.querySelectorAll('input[type="checkbox"]')).filter(x=>x.checked).map(x=>parseInt(x.value));
        await fetch('/api/rpc/update_user_roles', { method:'POST', headers:{'Content-Type':'application/json'}, body: JSON.stringify({ user_id: uid, role_ids: sel }) });
      };
    }
  }
  function renderUsers() {
    const term = (search && search.value || '').toLowerCase().trim();
    const users = term ? usersAll.filter(u => String(u.Username||'').toLowerCase().includes(term) || String(u.FullName||'').toLowerCase().includes(term)) : usersAll;
    body.innerHTML = users.map(u => {
      const rid = `roles_${u.UserID}`;
      return `
        <tr>
          <td>${u.Username}</td>
          <td>${u.FullName ?? ''}</td>
          <td>${u.IsActive ? '✓' : '✗'}</td>
          <td>
            <div id="${rid}" data-user="${u.UserID}">${roles.map(r=>`<label style="margin-right:8px; display:inline-flex; gap:6px; align-items:center;"><input type="checkbox" value="${r.RoleID}"> ${r.RoleName}${r.IsActive ? '' : ' (غیرفعال)'} <span><button class="btn btn-outline" data-act="toggle-role-inline" data-role="${r.RoleID}">فعال/غیرفعال</button><button class="btn btn-outline" data-act="edit-role-inline" data-role="${r.RoleID}">ویرایش</button><button class="btn btn-outline" data-act="del-role-inline" data-role="${r.RoleID}">حذف</button></span></label>`).join('')}</div>
            <button class="btn btn-outline" data-act="save-roles" data-id="${u.UserID}">ثبت نقش‌ها</button>
          </td>
        </tr>
      `;
    }).join('');
  }
  if (form && !form._init) {
    form._init = 1;
    form.addEventListener('submit', async (e) => {
      e.preventDefault();
      const data = Object.fromEntries(new FormData(form).entries());
      const payload = { username: data.username, full_name: data.full_name, is_active: parseInt(data.is_active||'1') };
      const r = await fetch('/api/admin/users', { method:'POST', headers:{'Content-Type':'application/json'}, body: JSON.stringify(payload) });
      if (r.ok) { form.reset(); await loadUsers(); }
    });
    document.addEventListener('click', async (e) => {
      const btn = e.target.closest('#admin-users-body [data-act="save-roles"]');
      if (!btn) {
        const toggleInline = e.target.closest('#admin-users-body [data-act="toggle-role-inline"]');
        if (toggleInline) {
          const roleId = parseInt(toggleInline.getAttribute('data-role'));
          const role = roles.find(x => x.RoleID === roleId);
          if (role) {
            await fetch(`/api/admin/roles?RoleID=eq.${roleId}`, { method:'PATCH', headers:{'Content-Type':'application/json'}, body: JSON.stringify({ RoleName: role.RoleName, IsActive: role.IsActive ? 0 : 1 }) });
            await loadRoles();
            await loadUsers();
          }
          return;
        }
        const editInline = e.target.closest('#admin-users-body [data-act="edit-role-inline"]');
        if (editInline) {
          const roleId = parseInt(editInline.getAttribute('data-role'));
          const role = roles.find(x => x.RoleID === roleId);
          if (role) {
            const newName = prompt('نام نقش جدید', role.RoleName) || role.RoleName;
            await fetch(`/api/admin/roles?RoleID=eq.${roleId}`, { method:'PATCH', headers:{'Content-Type':'application/json'}, body: JSON.stringify({ RoleName: newName, IsActive: role.IsActive ? 1 : 0 }) });
            await loadRoles();
            await loadUsers();
          }
          return;
        }
        const delInline = e.target.closest('#admin-users-body [data-act="del-role-inline"]');
        if (delInline) {
          const roleId = parseInt(delInline.getAttribute('data-role'));
          const ok = confirm('حذف این نقش انجام شود؟');
          if (ok) {
            const resp = await fetch(`/api/admin/roles?RoleID=eq.${roleId}`, { method:'DELETE' });
            if (!resp.ok) {
              try { const j = await resp.json(); alert(j.error || 'خطا در حذف نقش'); } catch(_) { alert('امکان حذف نقش نیست'); }
            }
            await loadRoles();
            await loadUsers();
          }
          return;
        }
        return;
      }
      const uid = parseInt(btn.getAttribute('data-id'));
      const div = document.getElementById(`roles_${uid}`);
      const sel = Array.from(div.querySelectorAll('input[type="checkbox"]')).filter(x=>x.checked).map(x=>parseInt(x.value));
      await fetch('/api/rpc/update_user_roles', { method:'POST', headers:{'Content-Type':'application/json'}, body: JSON.stringify({ user_id: uid, role_ids: sel }) });
      await loadUsers();
    });
    if (search) {
      search.addEventListener('input', () => renderUsers());
    }
  }
  await loadRoles();
  await loadUsers();
}

